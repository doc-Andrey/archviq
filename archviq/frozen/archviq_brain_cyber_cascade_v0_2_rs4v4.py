def ensemble_profile(finals: pd.DataFrame) -> pd.DataFrame:
    rows: List[Dict[str, Any]] = []
    for p, g in finals.groupby("parameter", sort=False):
        st = g["final_calibration_state"].to_numpy(float)
        pr = g["final_calibration_pressure"].to_numpy(float)
        pdef = PARAMETER_DEFINITIONS[p]
        rows.append({
            "parameter": p,
            "label": pdef["label"],
            "family": pdef["family"],
            "mode": pdef["mode"],
            "runtime_baseline": pdef.get("runtime_baseline", np.nan),
            "n_runs": int(len(g)),
            "state_median": float(np.median(st)),
            "state_min": float(np.min(st)),
            "state_max": float(np.max(st)),
            "state_iqr": float(np.percentile(st, 75) - np.percentile(st, 25)),
            "pressure_median": float(np.median(pr)),
            "pressure_min": float(np.min(pr)),
            "pressure_max": float(np.max(pr)),
        })
    return pd.DataFrame(rows)


def brain_ensemble(brain: pd.DataFrame) -> pd.DataFrame:
    run = brain.groupby(["shift_days", "width", "circuit"], as_index=False).agg(
        mean_exposure=("exposure_pressure", "mean"), peak_exposure=("exposure_pressure", "max")
    )
    rows = []
    for c, g in run.groupby("circuit", sort=False):
        rows.append({
            "circuit": c,
            "n_runs": int(len(g)),
            "mean_exposure_median": float(g["mean_exposure"].median()),
            "mean_exposure_min": float(g["mean_exposure"].min()),
            "mean_exposure_max": float(g["mean_exposure"].max()),
            "peak_exposure_median": float(g["peak_exposure"].median()),
            "peak_exposure_max": float(g["peak_exposure"].max()),
        })
    return pd.DataFrame(rows)


def window_summary(traj: pd.DataFrame, packet: pd.DataFrame) -> pd.DataFrame:
    pseq = packet.groupby(["shift_days", "width", "window"], as_index=False).agg(
        dpc_start=("dpc_start", "min"), dpc_end=("dpc_end", "max"),
        mean_atypicality=("atypicality", "mean"), mean_abrupt=("abrupt", "mean")
    )
    seq_map: Dict[Tuple[int, int, str], str] = {}
    for key, g in packet.groupby(["shift_days", "width", "window"]):
        seq_map[key] = " | ".join(g.sort_values("dpc_start")["regime"].astype(str))
    pseq["regime_sequence"] = [seq_map[(int(r.shift_days), int(r.width), str(r.window))] for r in pseq.itertuples()]

    mov = traj.groupby(["shift_days", "width", "window", "parameter"], as_index=False)["delta_state"].sum()
    rows = []
    for _, r in pseq.iterrows():
        gg = mov[(mov.shift_days == r.shift_days) & (mov.width == r.width) & (mov.window == r.window)].copy()
        gg["abs_delta"] = gg["delta_state"].abs()
        top = gg.sort_values("abs_delta", ascending=False).head(7)
        rows.append({**r.to_dict(), "top_parameter_changes": " | ".join(f"{x.parameter}:{x.delta_state:+.3f}" for x in top.itertuples())})
    return pd.DataFrame(rows)


def build_explanation_graph(contributors: List[Dict[str, Any]], ensemble: pd.DataFrame, top_n: int,
                            ablations: Sequence[str]) -> Dict[str, Any]:
    out: Dict[str, Any] = {
        "version": VERSION,
        "status": "experimental_hypothesis_graph",
        "warning": "Circuit and developmental mappings are hypotheses; natural EMF causality is not established.",
        "ablation": list(ablations),
        "parameters": {},
    }
    by_param: Dict[str, List[Dict[str, Any]]] = {}
    for x in contributors:
        by_param.setdefault(str(x["parameter"]), []).append(x)
    ens_map = {str(r.parameter): r._asdict() for r in ensemble.itertuples(index=False)}
    for p, arr in by_param.items():
        mode = PARAMETER_DEFINITIONS[p]["mode"]
        if mode == "directional":
            ranked = sorted(arr, key=lambda z: abs(float(z["delta_state"])), reverse=True)
            metric = "abs(delta_state)"
        else:
            ranked = sorted(arr, key=lambda z: float(z["packet_pressure"]), reverse=True)
            metric = "packet_pressure"
        out["parameters"][p] = {
            "definition": PARAMETER_DEFINITIONS[p],
            "ensemble": ens_map.get(p, {}),
            "ranking_metric": metric,
            "top_contributors": ranked[:top_n],
        }
    return out


def h_star_vector(ensemble: pd.DataFrame) -> Dict[str, Any]:
    # H* is represented as the full individual set-point vector, not a scalar.
    vector: Dict[str, Any] = {}
    for r in ensemble.itertuples(index=False):
        vector[str(r.parameter)] = {
            "mode": str(r.mode),
            "family": str(r.family),
            "calibration_state_median": float(r.state_median),
            "calibration_state_range": [float(r.state_min), float(r.state_max)],
            "calibration_pressure_median": float(r.pressure_median),
            "runtime_baseline_reference": None if pd.isna(r.runtime_baseline) else float(r.runtime_baseline),
        }
    return {
        "version": VERSION,
        "definition": "H* is the complete machine-parameter set-point vector. No single H* scalar is inferred.",
        "runtime_projection": "disabled: no validated law maps calibration state to literal RS4 threshold values",
        "vector": vector,
    }


def parameter_definition_table(cfg: Mapping[str, Any]) -> pd.DataFrame:
    rows = []
    for p, d in cfg["parameter_definitions"].items():
        rows.append({"parameter": p, **d})
    return pd.DataFrame(rows)


def developmental_map_table(cfg: Mapping[str, Any]) -> pd.DataFrame:
    rows = []
    for w in WINDOW_ORDER:
        for p in cfg["parameter_definitions"]:
            gate = developmental_gate(w, p, cfg)
            if gate > 0:
                rows.append({"window": w, "parameter": p, "sensitivity": gate, "mode": cfg["parameter_definitions"][p]["mode"], "family": cfg["parameter_definitions"][p]["family"]})
    return pd.DataFrame(rows)

