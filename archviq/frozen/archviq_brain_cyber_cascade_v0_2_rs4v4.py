def normalize_weights(m: Mapping[str, float]) -> Dict[str, float]:
    vals = {k: float(v) for k, v in m.items() if abs(float(v)) > EPS}
    s = sum(abs(v) for v in vals.values())
    return vals if s <= EPS else {k: v / s for k, v in vals.items()}


def circuit_exposure(window: str, drivers: Mapping[str, float], cfg: Mapping[str, Any]) -> Dict[str, float]:
    sens = cfg["window_circuit_sensitivity"][window]
    pe = cfg["packet_exposure"]
    base = float(np.clip(float(pe["atypicality_weight"]) * drivers["atypicality"]
                         + float(pe["abrupt_weight"]) * abs(drivers["abrupt"]), 0.0, 1.0))
    return {c: float(np.clip(float(sens.get(c, 0.0)) * base, 0.0, 1.0)) for c in cfg["circuits"]}


def parameter_circuit_pressure(circuit_pressure: Mapping[str, float], param: str,
                               cfg: Mapping[str, Any]) -> float:
    w = normalize_weights(cfg["parameter_circuit_map"][param])
    return float(np.clip(sum(float(wi) * float(circuit_pressure.get(c, 0.0)) for c, wi in w.items()), 0.0, 1.0))


def developmental_gate(window: str, param: str, cfg: Mapping[str, Any]) -> float:
    return float(cfg["window_parameter_sensitivity"].get(window, {}).get(param, 0.0))


def directional_rule_score(drivers: Mapping[str, float], param: str, cfg: Mapping[str, Any]) -> float:
    mode = str(cfg["parameter_definitions"][param]["mode"])
    if mode != "directional":
        return 0.0
    w = cfg["parameter_driver_weights"].get(param, {})
    if not w:
        return 0.0
    denom = sum(abs(float(x)) for x in w.values())
    if denom <= EPS:
        return 0.0
    score = sum(float(weight) * float(drivers.get(name, 0.0)) for name, weight in w.items()) / denom
    return float(np.clip(score, -1.0, 1.0))

# =============================================================================
# Cascade + explicit parameter-family hysteresis
# =============================================================================

def pressure_update(state: float, pressure: float, cfg: Mapping[str, Any]) -> float:
    su = cfg["state_update"]
    retain = float(su["pressure_retention"])
    alpha = float(su["pressure_alpha"])
    return float(np.clip(retain * state + alpha * pressure * (1.0 - state), 0.0, 1.0))


def hysteretic_update(state: float, drive: float, family_hysteresis_state: float,
                      cfg: Mapping[str, Any], hysteresis_enabled: bool = True) -> Tuple[float, str, float, float]:
    su = cfg["state_update"]
    activation = float(su["activation_threshold"])
    retain = float(su["retention"])
    clip = float(su["state_clip"])

    # Cascade: established same-sign state slightly amplifies repeated same-direction input.
    cascade_gain = 1.0 + float(su["same_sign_cascade_gain"]) * min(abs(state), 1.5) if (state * drive > 0) else 1.0
    drive_eff = float(np.clip(drive * cascade_gain, -1.0, 1.0))

    if abs(drive_eff) < activation:
        return float(np.clip(state * retain, -clip, clip)), "HOLD_NEUTRAL", activation, drive_eff

    same_sign = abs(state) < EPS or np.sign(state) == np.sign(drive_eff)
    if same_sign:
        alpha = float(su["alpha_from_zero"] if abs(state) < EPS else su["alpha_same_sign"])
        new = state + alpha * (drive_eff - state)
        return float(np.clip(new, -clip, clip)), "UPDATE_SAME_SIGN", activation, drive_eff

    if hysteresis_enabled:
        reverse_thr = (
            float(su["reverse_threshold_base"])
            + float(su["reverse_hysteresis_coupling"]) * max(family_hysteresis_state, 0.0)
            + float(su["reverse_state_penalty"]) * min(abs(state), 1.5)
        )
    else:
        reverse_thr = activation

    if abs(drive_eff) < reverse_thr:
        return float(np.clip(state * retain, -clip, clip)), "HOLD_HYSTERESIS", reverse_thr, drive_eff

    alpha = float(su["alpha_reverse"])
    new = state + alpha * (drive_eff - state)
    return float(np.clip(new, -clip, clip)), "UPDATE_REVERSAL", reverse_thr, drive_eff


def ablation_targeted(param: str, ablations: Sequence[str]) -> bool:
    for a in ablations:
        if a in ABLATION_TARGETS and param in ABLATION_TARGETS[a]:
            return True
    return False


def run_one(df_run: pd.DataFrame, cfg: Mapping[str, Any], ablations: Sequence[str] = ()) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, List[Dict[str, Any]], pd.DataFrame]:
    params = list(cfg["parameter_definitions"].keys())
    circuits = list(cfg["circuits"])
    states = {p: 0.0 for p in params}
    pressures = {p: 0.0 for p in params}

    packet_rows: List[Dict[str, Any]] = []
    brain_rows: List[Dict[str, Any]] = []
    traj_rows: List[Dict[str, Any]] = []
    contributors: List[Dict[str, Any]] = []

    g = df_run.copy()
    g["_wo"] = g["window"].map(WINDOW_ORDER)
    g = g.sort_values(["dpc_start", "_wo", "packet_index"]).reset_index(drop=True)

    prev_regime: str | None = None
    prev2_regime: str | None = None
    hyst_enabled = "HYSTERESIS" not in set(ablations)

    for step, (_, row) in enumerate(g.iterrows()):
        drivers = packet_drivers(row, prev_regime, prev2_regime, cfg)
        cexp = circuit_exposure(str(row["window"]), drivers, cfg)
        base_meta = {
            "shift_days": int(row.get("shift_days", 0)),
            "width": int(row["width"]),
            "step": int(step),
            "window": str(row["window"]),
            "packet_index": int(row["packet_index"]),
            "dpc_start": int(row["dpc_start"]),
            "dpc_end": int(row["dpc_end"]),
            "date_start": str(row.get("date_start", "")),
            "date_end": str(row.get("date_end", "")),
            "regime": str(row.get("regime", "")),
            "transition": str(row.get("transition", "")),
        }

        pr = dict(base_meta)
        pr.update(drivers)
        packet_rows.append(pr)
        for c in circuits:
            brain_rows.append({**base_meta, "circuit": c, "exposure_pressure": cexp[c]})

        # Snapshot old state so all parameters update simultaneously and do not depend
        # on arbitrary dictionary order within the same packet.
        old_states = states.copy()
        old_pressures = pressures.copy()
        proposal: Dict[str, Dict[str, Any]] = {}

        for p in params:
            pdef = cfg["parameter_definitions"][p]
            mode = str(pdef["mode"])
            circuit_p = parameter_circuit_pressure(cexp, p, cfg)
            gate = developmental_gate(str(row["window"]), p, cfg)
            packet_pressure = float(np.clip(circuit_p * gate, 0.0, 1.0))

            # Engineering ablation of module families: zero their developmental drive.
            if ablation_targeted(p, ablations):
                packet_pressure = 0.0

            rule = directional_rule_score(drivers, p, cfg)
            signed_drive = float(rule * packet_pressure) if mode == "directional" else 0.0

            hyst_link = cfg["parameter_hysteresis_link"].get(p)
            family_h = float(old_states.get(hyst_link, 0.0)) if hyst_link else 0.0
            new_pressure = pressure_update(old_pressures[p], packet_pressure, cfg)

            if mode == "directional":
                new_state, event, threshold, drive_eff = hysteretic_update(
                    old_states[p], signed_drive, family_h, cfg, hysteresis_enabled=hyst_enabled
                )
            else:
                new_state, event, threshold, drive_eff = old_states[p], "PRESSURE_ONLY", np.nan, 0.0

            proposal[p] = {
                "mode": mode,
                "family": str(pdef.get("family", "")),
                "circuit_pressure": circuit_p,
                "developmental_gate": gate,
                "packet_pressure": packet_pressure,
                "rule_score": rule,
                "signed_drive": signed_drive,
                "drive_effective": drive_eff,
                "family_hysteresis_parameter": hyst_link or "",
                "family_hysteresis_state": family_h,
                "state_before": old_states[p],
                "state_after": new_state,
                "pressure_before": old_pressures[p],
                "pressure_after": new_pressure,
                "delta_state": new_state - old_states[p],
                "hysteresis_event": event,
                "effective_threshold": threshold,
            }

        # Commit simultaneously.
        for p, v in proposal.items():
            states[p] = float(v["state_after"])
            pressures[p] = float(v["pressure_after"])
            traj_rows.append({**base_meta, "parameter": p, **v})
            contributors.append({
                **base_meta,
                "parameter": p,
                "mode": v["mode"],
                "family": v["family"],
                "packet_pressure": v["packet_pressure"],
                "rule_score": v["rule_score"],
                "signed_drive": v["signed_drive"],
                "drive_effective": v["drive_effective"],
                "delta_state": v["delta_state"],
                "hysteresis_event": v["hysteresis_event"],
                "effective_threshold": None if not np.isfinite(v["effective_threshold"]) else float(v["effective_threshold"]),
                "drivers": {k: float(x) for k, x in drivers.items()},
                "top_circuit_pressures": sorted(
                    [{"circuit": c, "pressure": float(cexp[c])} for c in circuits],
                    key=lambda x: x["pressure"], reverse=True
                )[:4],
            })

        prev2_regime = prev_regime
        prev_regime = str(row.get("regime", ""))

    shift = int(g.iloc[0].get("shift_days", 0)) if len(g) else 0
    width = int(g.iloc[0]["width"]) if len(g) else -1
    finals = []
    for p in params:
        pdef = cfg["parameter_definitions"][p]
        finals.append({
            "shift_days": shift,
            "width": width,
            "parameter": p,
            "label": pdef["label"],
            "family": pdef["family"],
            "mode": pdef["mode"],
            "runtime_baseline": pdef.get("runtime_baseline", np.nan),
            "final_calibration_state": states[p],
            "final_calibration_pressure": pressures[p],
            "ablation": "+".join(sorted(set(ablations))) if ablations else "NONE",
        })
    return pd.DataFrame(packet_rows), pd.DataFrame(brain_rows), pd.DataFrame(traj_rows), contributors, pd.DataFrame(finals)

