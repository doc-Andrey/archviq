def pct_signed(x: float, cfg: Mapping[str, Any]) -> float:
    if not np.isfinite(x):
        return 0.0
    tr = cfg["driver_transform"]
    return float(np.clip((float(x) - float(tr["percentile_center"])) / float(tr["percentile_scale"]),
                         -float(tr["clip"]), float(tr["clip"])))


def regime_flags(prev_regime: str | None, regime: str, prev2_regime: str | None = None) -> Dict[str, float]:
    prev = prev_regime or ""
    prev2 = prev2_regime or ""
    is_burst = regime in BURST_REGIMES
    was_burst = prev in BURST_REGIMES
    is_persistent = regime in PERSISTENT_REGIMES
    was_persistent = prev in PERSISTENT_REGIMES
    is_reversal = regime in REVERSAL_REGIMES
    was_reversal = prev in REVERSAL_REGIMES
    is_quiet = regime in QUIET_REGIMES
    was_quiet = prev in QUIET_REGIMES
    return {
        "quiet_to_burst": float(was_quiet and is_burst),
        "burst_to_quiet": float(was_burst and is_quiet),
        "quiet_after_burst": float(is_quiet and (was_burst or prev2 in BURST_REGIMES)),
        "persistent_to_reversal": float(was_persistent and is_reversal),
        "reversal_to_persistent": float(was_reversal and is_persistent),
        "repeated_burst": float(was_burst and is_burst),
        "repeated_reversal": float(was_reversal and is_reversal),
        "sustained_hold": float(was_persistent and is_persistent),
    }


def packet_drivers(row: Mapping[str, Any], prev_regime: str | None, prev2_regime: str | None,
                   cfg: Mapping[str, Any]) -> Dict[str, float]:
    qA = pct_signed(float(row.get("A_cond_pct", np.nan)), cfg)
    qV = pct_signed(float(row.get("V_cond_pct", np.nan)), cfg)
    qJ = pct_signed(float(row.get("JUMP_cond_pct", np.nan)), cfg)
    qAcc = pct_signed(float(row.get("ACC_cond_pct", np.nan)), cfg)
    qJerk = pct_signed(float(row.get("JERK_cond_pct", np.nan)), cfg)
    qE = pct_signed(float(row.get("E_cond_pct", np.nan)), cfg)
    qR = pct_signed(float(row.get("R_cond_pct", np.nan)), cfg)
    qD = pct_signed(float(row.get("D_cond_pct", np.nan)), cfg)
    qDir = pct_signed(float(row.get("BABS_cond_pct", np.nan)), cfg)
    qLoad = pct_signed(float(row.get("dynamic_load_pct", np.nan)), cfg)

    mag = np.array([qA, qV, qJ, qAcc, qJerk, qE], float)
    abrupt_arr = np.array([qAcc, qJerk, qJ], float)
    d = {
        "load": qLoad,
        "quiet": -qLoad,
        "magnitude": float(np.mean(mag)),
        "atypicality": float(np.mean(np.abs(mag))),
        "abrupt": float(np.mean(abrupt_arr)),
        "energy": qE,
        "persistence": qD,
        "reversal": qR,
        "directionality": qDir,
    }
    d.update(regime_flags(prev_regime, str(row.get("regime", "")), prev2_regime))
    return d

