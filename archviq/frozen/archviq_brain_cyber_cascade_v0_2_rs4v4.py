def run_model(df: pd.DataFrame, cfg: Mapping[str, Any], ablations: Sequence[str], top_n: int) -> Dict[str, Any]:
    all_packet: List[pd.DataFrame] = []
    all_brain: List[pd.DataFrame] = []
    all_traj: List[pd.DataFrame] = []
    all_contrib: List[Dict[str, Any]] = []
    all_finals: List[pd.DataFrame] = []

    for (_, _), g in df.groupby(["shift_days", "width"], sort=True):
        p, b, t, contrib, f = run_one(g, cfg, ablations=ablations)
        all_packet.append(p); all_brain.append(b); all_traj.append(t); all_contrib.extend(contrib); all_finals.append(f)

    packet_df = pd.concat(all_packet, ignore_index=True)
    brain_df = pd.concat(all_brain, ignore_index=True)
    traj_df = pd.concat(all_traj, ignore_index=True)
    finals_df = pd.concat(all_finals, ignore_index=True)
    ens = ensemble_profile(finals_df)
    bens = brain_ensemble(brain_df)
    wsum = window_summary(traj_df, packet_df)
    graph = build_explanation_graph(all_contrib, ens, max(1, top_n), ablations)
    return {
        "packet": packet_df,
        "brain": brain_df,
        "trajectory": traj_df,
        "finals": finals_df,
        "ensemble": ens,
        "brain_ensemble": bens,
        "window_summary": wsum,
        "graph": graph,
        "hstar": h_star_vector(ens),
    }


def ablation_suite(df: pd.DataFrame, cfg: Mapping[str, Any], baseline_ens: pd.DataFrame, top_n: int) -> pd.DataFrame:
    base = baseline_ens.set_index("parameter")
    suite = ["NU", "U", "GAMMA", "HYSTERESIS", "PROVENANCE", "W_MIN"]
    rows: List[Dict[str, Any]] = []
    for lesion in suite:
        res = run_model(df, cfg, [lesion], top_n=top_n)
        ens = res["ensemble"].set_index("parameter")
        for p in base.index:
            b = base.loc[p]
            a = ens.loc[p]
            rows.append({
                "ablation": lesion,
                "parameter": p,
                "mode": b["mode"],
                "baseline_state_median": float(b["state_median"]),
                "ablated_state_median": float(a["state_median"]),
                "delta_state": float(a["state_median"] - b["state_median"]),
                "baseline_pressure_median": float(b["pressure_median"]),
                "ablated_pressure_median": float(a["pressure_median"]),
                "delta_pressure": float(a["pressure_median"] - b["pressure_median"]),
                "note": (
                    "structural invariant/no numeric developmental lesion in v0.2"
                    if lesion in {"PROVENANCE", "W_MIN"}
                    else "engineering sensitivity only; not behavioral lesion validation"
                ),
            })
    return pd.DataFrame(rows)


